"""Evidence-bound remediation proposals and human decision contracts."""

from datetime import datetime
from typing import Literal

from pydantic import Field, field_validator

from app.schemas.base import StrictModel
from app.schemas.inventory import Evidence

RemediationAction = Literal[
    "upgrade", "replace", "remove", "pin", "mitigate", "block", "security_review"
]
ProposalStatus = Literal["PENDING", "APPROVED", "REJECTED", "SUPERSEDED"]
DecisionType = Literal["APPROVED", "REJECTED"]

# Legacy free-form factors. Retained only so decisions recorded before structured
# assessments existed still serialize; new decisions never populate them.
DecisionFactor = Literal[
    "SECURITY_RISK",
    "EXPLOITABILITY",
    "DEPENDENCY_PATH",
    "APPLICATION_CONTEXT",
    "COMPATIBILITY",
    "BUSINESS_IMPACT",
    "TEST_EVIDENCE",
    "SOURCE_CONFIDENCE",
    "INCOMPLETE_EVIDENCE",
    "LICENSE_OR_POLICY",
    "OPERATIONAL_RISK",
    "ROLLBACK_READINESS",
    "ALTERNATIVE_AVAILABLE",
    "OTHER",
]

# Structured reviewer assessment. Every dimension accepts UNKNOWN: an honest
# "I don't know" is a valid, auditable answer and must never be coerced into
# invented context.
ProductionUsage = Literal["IN_PRODUCTION", "NOT_IN_PRODUCTION", "DEV_OR_TEST_ONLY", "UNKNOWN"]
Compatibility = Literal["COMPATIBLE", "MINOR_CHANGES", "BREAKING", "UNKNOWN"]
TestConfidence = Literal["HIGH", "PARTIAL", "NONE", "UNKNOWN"]
Ownership = Literal["OWNER_CONFIRMED", "OWNER_IDENTIFIED", "NO_OWNER", "UNKNOWN"]
Alternatives = Literal[
    "ALTERNATIVE_PREFERRED", "ALTERNATIVE_AVAILABLE", "NO_ALTERNATIVE", "UNKNOWN"
]
Timing = Literal["IMMEDIATE", "NEXT_RELEASE", "BACKLOG", "UNKNOWN"]

EXPLANATION_TEMPLATE_VERSION = "assessment-v1"
NOTE_MAX_LENGTH = 280


class ReviewAssessment(StrictModel):
    production_usage: ProductionUsage
    compatibility: Compatibility
    test_confidence: TestConfidence
    ownership: Ownership
    alternatives: Alternatives
    timing: Timing


class RemediationDecisionCreate(StrictModel):
    decision: DecisionType
    decided_by: str = Field(min_length=2, max_length=200)
    assessment: ReviewAssessment
    note: str | None = Field(default=None, max_length=NOTE_MAX_LENGTH)
    external_reference: str | None = Field(default=None, max_length=500)
    expected_proposal_version: int = Field(ge=1)

    @field_validator("decided_by")
    @classmethod
    def strip_required(cls, value: str) -> str:
        stripped = value.strip()
        if len(stripped) < 2:
            raise ValueError("Reviewer identity must contain at least two characters")
        return stripped

    @field_validator("note", "external_reference")
    @classmethod
    def strip_optional(cls, value: str | None) -> str | None:
        # Blank optional text is simply absent, not an error.
        if value is None:
            return None
        return value.strip() or None


class RemediationDecision(StrictModel):
    decision_id: str
    proposal_id: str
    decision: DecisionType
    decided_by: str
    # For structured decisions this is generated by Kestral from the assessment;
    # for legacy decisions it is the reviewer's original free text.
    reason: str
    reason_source: Literal["GENERATED", "REVIEWER_WRITTEN"]
    explanation_template: str | None
    assessment: ReviewAssessment | None
    note: str | None
    factors: list[DecisionFactor]
    conditions: str | None
    alternative: str | None
    external_reference: str | None
    repository_commit: str
    finding_digest: str
    proposal_digest: str
    decided_at: datetime


class RemediationProposal(StrictModel):
    proposal_id: str
    scan_id: str
    finding_id: str
    action: RemediationAction
    subject_label: str
    current_value: str | None
    proposed_value: str | None
    recommendation: str
    rationale: str
    expected_risk_reduction: Literal["high", "medium", "low", "unknown"]
    compatibility_impact: Literal["high", "medium", "low", "unknown"]
    evidence: list[Evidence] = Field(min_length=1)
    uncertainty: list[str]
    repository_commit: str
    finding_digest: str
    proposal_digest: str
    status: ProposalStatus
    version: int = Field(ge=1)
    created_at: datetime
    decision: RemediationDecision | None = None


class RemediationList(StrictModel):
    schema_version: Literal["1.0"] = "1.0"
    scan_id: str
    proposals: list[RemediationProposal]

"""AI analyst contract (optional capability): bounded investigation of one finding.

The model only drafts an explanation and a remediation proposal (``AiDraft``). Identity,
the original finding, fixed-version verification, claim verification and the tool trace
are filled in and checked by application code (``AiRecommendation``). A recommendation is
never an applied or validated change.
"""

from datetime import datetime
from typing import Annotated, Literal

from pydantic import Field, JsonValue

from app.schemas.base import StrictModel

PROMPT_VERSION = "1.0"

ClaimKind = Literal["verified_fact", "model_interpretation", "recommendation", "unknown"]
StrategyType = Literal[
    "upgrade",
    "upgrade_parent",
    "override",
    "remove",
    "replace",
    "config_mitigation",
    "pin_source",
    "compensating_control",
    "manual_review",
]
DraftStatus = Literal[
    "recommendation_ready", "needs_human_review", "insufficient_evidence", "no_verified_fix"
]
AnalysisStatus = Literal[
    "queued",
    "running",
    "recommendation_ready",
    "needs_human_review",
    "insufficient_evidence",
    "no_verified_fix",
    "ai_unavailable",
    "validation_failed",
    "failed",
]
Level = Literal["low", "medium", "high"]

ShortText = Annotated[str, Field(max_length=300)]
LongText = Annotated[str, Field(max_length=2500)]
EvidenceRef = Annotated[str, Field(pattern=r"^ev-\d{1,3}$")]


# ---------------------------------------------------------------------------
# What the model writes (validated locally after structured output)
# ---------------------------------------------------------------------------


class DraftRemediation(StrictModel):
    type: StrategyType
    target_component_id: str | None
    target_version: Annotated[str, Field(max_length=100)] | None
    steps: Annotated[list[ShortText], Field(max_length=10)]
    evidence_refs: Annotated[list[EvidenceRef], Field(max_length=20)]


class DraftAlternative(StrictModel):
    type: StrategyType
    description: ShortText
    tradeoffs: ShortText


class DraftCompatibility(StrictModel):
    breaking_change_risk: Literal["low", "medium", "high", "unknown"]
    notes: Annotated[list[ShortText], Field(max_length=8)]
    required_checks: Annotated[list[ShortText], Field(max_length=8)]


class DraftClaim(StrictModel):
    claim: ShortText
    kind: ClaimKind
    evidence_refs: Annotated[list[EvidenceRef], Field(max_length=10)]


class AiDraft(StrictModel):
    status: DraftStatus
    title: Annotated[str, Field(max_length=200)]
    summary: LongText
    why_it_matters: LongText
    recommended_remediation: DraftRemediation
    alternatives: Annotated[list[DraftAlternative], Field(max_length=4)]
    compatibility: DraftCompatibility
    risks_and_tradeoffs: Annotated[list[ShortText], Field(max_length=8)]
    validation_plan: Annotated[list[ShortText], Field(max_length=10)]
    residual_risk: Annotated[list[ShortText], Field(max_length=8)]
    claims: Annotated[list[DraftClaim], Field(max_length=20)]
    unknowns: Annotated[list[ShortText], Field(max_length=10)]
    confidence: Level


# ---------------------------------------------------------------------------
# What the API serves
# ---------------------------------------------------------------------------


class EvidenceItem(StrictModel):
    """A fact the analysis may cite, with where it came from. IDs are per analysis."""

    id: str
    kind: str
    source: str
    summary: str
    external: bool = False


class ToolCall(StrictModel):
    index: int
    name: str
    arguments: dict[str, JsonValue]
    status: Literal["ok", "error", "rejected", "budget_exhausted"]
    external: bool
    evidence_ids: list[str]
    duration_ms: int
    message: str | None = None


class ValidationCheck(StrictModel):
    id: str
    status: Literal["passed", "failed", "not_run", "warning"]
    detail: str


class ValidationResult(StrictModel):
    status: Literal["passed", "partial", "failed"]
    checks: list[ValidationCheck]
    blocking_issues: list[str]
    warnings: list[str]


class OriginalFinding(StrictModel):
    """Copied from the canonical finding; never generated by the model."""

    finding_id: str
    kind: str
    title: str
    advisory_ids: list[str]
    component_id: str | None
    package: str
    ecosystem: str | None
    installed_version: str | None
    severity: str | None
    severity_source: str | None
    cvss_base_score: float | None
    priority_score: int | None
    priority_band: str | None
    risk_level: str | None
    fixed_versions: list[str]


class Remediation(DraftRemediation):
    fixed_version_verified: bool
    version_source: str | None
    version_source_url: str | None


class Compatibility(DraftCompatibility):
    manifest_status: Literal["accepts", "rejects", "not_checked"]
    manifest_detail: str


class Claim(DraftClaim):
    verification_status: Literal["verified", "unverified", "rejected"]


class Patch(StrictModel):
    available: Literal[False] = False
    diff: None = None
    files_affected: list[str] = Field(default_factory=list)


class ModelMetadata(StrictModel):
    provider: str
    model: str
    prompt_version: str
    effort: str | None
    input_tokens: int
    output_tokens: int


class AiRecommendation(StrictModel):
    schema_version: Literal["1.0"] = "1.0"
    scan_id: str
    finding_id: str
    commit_sha: str | None
    status: AnalysisStatus
    title: str
    summary: str
    why_it_matters: str
    original_finding: OriginalFinding
    recommended_remediation: Remediation
    alternatives: list[DraftAlternative]
    compatibility: Compatibility
    risks_and_tradeoffs: list[str]
    validation_plan: list[str]
    residual_risk: list[str]
    claims: list[Claim]
    unknowns: list[str]
    confidence: Level
    evidence: list[EvidenceItem]
    human_approval_required: Literal[True] = True
    patch: Patch = Field(default_factory=Patch)
    tool_trace: list[ToolCall]
    stop_reason: str
    validation: ValidationResult
    model_metadata: ModelMetadata


class AiDecision(StrictModel):
    decision: Literal["approved", "rejected"]
    note: str | None
    decided_at: datetime


class AiDecisionRequest(StrictModel):
    decision: Literal["approved", "rejected"]
    note: Annotated[str, Field(max_length=1000)] | None = None


class AiAnalysis(StrictModel):
    analysis_id: str
    scan_id: str
    finding_id: str
    status: AnalysisStatus
    stale: bool
    cached: bool
    error: str | None
    created_at: datetime
    finished_at: datetime | None
    recommendation: AiRecommendation | None
    decision: AiDecision | None


class AiStatus(StrictModel):
    enabled: bool
    configured: bool
    provider: str
    api_key_env: str
    model: str
    prompt_version: str
    tool_budget: int
    data_notice: str

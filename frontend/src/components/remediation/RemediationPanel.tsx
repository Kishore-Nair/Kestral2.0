"use client";

import { useEffect, useState } from "react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { scanService } from "@/services/scanService";
import { classifyError } from "@/services/errors";
import type { ScanApi } from "@/services/api";
import type { DecisionType, RemediationProposal, ReviewAssessment } from "@/types/remediation";
import { NOTE_MAX_LENGTH } from "@/types/remediation";
import { useConfirmBeforeUnload } from "@/hooks/usePersistentScanId";

type Dimension = keyof ReviewAssessment;
type Draft = { [K in Dimension]: ReviewAssessment[K] | null };

/** Each question offers concrete answers plus an always-valid "Unknown". */
const QUESTIONS: Array<{ key: Dimension; label: string; options: Array<[string, string]> }> = [
  { key: "production_usage", label: "Is the affected code used in production?", options: [
    ["IN_PRODUCTION", "Yes, in production"], ["NOT_IN_PRODUCTION", "Not in production"], ["DEV_OR_TEST_ONLY", "Dev / test only"]] },
  { key: "compatibility", label: "Will the change be compatible?", options: [
    ["COMPATIBLE", "Compatible"], ["MINOR_CHANGES", "Minor changes needed"], ["BREAKING", "Breaking"]] },
  { key: "test_confidence", label: "How well do tests cover the affected code?", options: [
    ["HIGH", "High confidence"], ["PARTIAL", "Partial"], ["NONE", "No tests"]] },
  { key: "ownership", label: "Who owns the affected code?", options: [
    ["OWNER_CONFIRMED", "Owner confirmed"], ["OWNER_IDENTIFIED", "Owner known, not confirmed"], ["NO_OWNER", "No owner"]] },
  { key: "alternatives", label: "Is there an alternative remediation?", options: [
    ["ALTERNATIVE_PREFERRED", "Alternative preferred"], ["ALTERNATIVE_AVAILABLE", "Alternative exists"], ["NO_ALTERNATIVE", "No viable alternative"]] },
  { key: "timing", label: "When should this be acted on?", options: [
    ["IMMEDIATE", "Immediately"], ["NEXT_RELEASE", "Next release"], ["BACKLOG", "Backlog"]] },
];

const EMPTY: Draft = { production_usage: null, compatibility: null, test_confidence: null, ownership: null, alternatives: null, timing: null };
const optionLabel = (key: Dimension, value: string) =>
  value === "UNKNOWN" ? "Unknown" : QUESTIONS.find((q) => q.key === key)?.options.find(([v]) => v === value)?.[1] ?? value;

function DecisionRecord({ proposal }: { proposal: RemediationProposal }) {
  const decision = proposal.decision;
  if (!decision) return null;
  const assessment = decision.assessment;
  return (
    <div className="grid gap-2 rounded-md border bg-muted/40 p-3 text-sm">
      <div className="flex flex-wrap items-center gap-2">
        <Badge variant={decision.decision === "APPROVED" ? "secondary" : "destructive"}>{decision.decision}</Badge>
        <span>by {decision.decided_by}</span>
        <span className="text-xs text-muted-foreground">{new Date(decision.decided_at).toLocaleString()}</span>
      </div>
      <p>
        <span className="font-medium">{decision.reason_source === "GENERATED" ? "Audit explanation:" : "Reason:"}</span> {decision.reason}
      </p>
      {decision.reason_source === "GENERATED" && <p className="text-xs text-muted-foreground">Generated by Kestral from the reviewer&apos;s selections ({decision.explanation_template}).</p>}
      {assessment && (
        <dl className="grid gap-1 text-xs sm:grid-cols-2">
          {QUESTIONS.map((q) => (
            <div key={q.key} className="flex gap-1"><dt className="text-muted-foreground">{q.label}</dt><dd className="font-medium">{optionLabel(q.key, assessment[q.key])}</dd></div>
          ))}
        </dl>
      )}
      {decision.factors.length > 0 && <p className="text-xs text-muted-foreground">Factors: {decision.factors.map((f) => f.replaceAll("_", " ")).join(" · ")}</p>}
      {decision.conditions && <p><span className="font-medium">Conditions:</span> {decision.conditions}</p>}
      {decision.alternative && <p><span className="font-medium">Alternative:</span> {decision.alternative}</p>}
      {decision.external_reference && <p><span className="font-medium">Reference:</span> {decision.external_reference}</p>}
      <p className="font-mono text-xs text-muted-foreground">Bound to commit {decision.repository_commit.slice(0, 12)}</p>
    </div>
  );
}

function DecisionForm({ scanId, proposal, service, onDecided }: {
  scanId: string; proposal: RemediationProposal; service: ScanApi;
  onDecided: (value: RemediationProposal) => void;
}) {
  const [decision, setDecision] = useState<DecisionType>("APPROVED");
  const [reviewer, setReviewer] = useState("");
  const [draft, setDraft] = useState<Draft>(EMPTY);
  const [note, setNote] = useState("");
  const [reference, setReference] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  // An unsubmitted decision lives only in memory, so confirm before a refresh discards it.
  const dirty = reviewer.trim() !== "" || note.trim() !== "" || reference.trim() !== ""
    || QUESTIONS.some((q) => draft[q.key] !== null);
  useConfirmBeforeUnload(dirty && !busy);
  const unanswered = QUESTIONS.filter((q) => draft[q.key] === null);
  const valid = reviewer.trim().length >= 2 && unanswered.length === 0 && note.length <= NOTE_MAX_LENGTH;
  const choose = (key: Dimension, value: string) => setDraft((d) => ({ ...d, [key]: value }));
  const markRemainingUnknown = () => setDraft((d) =>
    Object.fromEntries(Object.entries(d).map(([k, v]) => [k, v ?? "UNKNOWN"])) as Draft);

  const submit = async () => {
    if (!valid) { setError("Provide reviewer identity and answer every question (\"Unknown\" is a valid answer)."); return; }
    const verb = decision === "APPROVED" ? "approve" : "reject";
    if (!window.confirm(`You are about to ${verb} this exact proposal for commit ${proposal.repository_commit.slice(0, 12)}. This records an audit decision but does not modify the repository. Continue?`)) return;
    setBusy(true); setError(null);
    try {
      onDecided(await service.decideRemediation(scanId, proposal.proposal_id, {
        decision, decided_by: reviewer.trim(), assessment: draft as ReviewAssessment,
        note: note.trim() || null, external_reference: reference.trim() || null,
        expected_proposal_version: proposal.version,
      }));
    } catch (err) { setError(classifyError(err).message); } finally { setBusy(false); }
  };

  return (
    <div className="grid gap-3 rounded-md border p-3">
      <p className="text-xs text-muted-foreground">Reviewer identity is self-declared in this prototype and is not authenticated.</p>
      <div className="flex gap-2" role="group" aria-label="Decision">
        <Button size="sm" aria-pressed={decision === "APPROVED"} variant={decision === "APPROVED" ? "default" : "outline"} onClick={() => setDecision("APPROVED")}>Approve</Button>
        <Button size="sm" aria-pressed={decision === "REJECTED"} variant={decision === "REJECTED" ? "destructive" : "outline"} onClick={() => setDecision("REJECTED")}>Reject</Button>
      </div>
      <label className="grid gap-1 text-sm">Reviewer identity<Input value={reviewer} onChange={(e) => setReviewer(e.target.value)} placeholder="name or email" /></label>
      <p className="text-xs text-muted-foreground">Answer what you know. &quot;Unknown&quot; is an honest, valid answer. Kestral writes the audit explanation from your selections.</p>
      {QUESTIONS.map((q) => (
        <fieldset key={q.key} className="grid gap-1">
          <legend className="text-sm font-medium">{q.label}</legend>
          <div className="flex flex-wrap gap-2">
            {[...q.options, ["UNKNOWN", "Unknown"] as [string, string]].map(([value, label]) => (
              <label key={value} className="flex cursor-pointer items-center gap-1 rounded border px-2 py-1 text-xs has-[:checked]:border-primary has-[:checked]:bg-primary/10 has-[:focus-visible]:ring-2 has-[:focus-visible]:ring-ring">
                <input type="radio" name={`${proposal.proposal_id}-${q.key}`} value={value} checked={draft[q.key] === value} onChange={() => choose(q.key, value)} />{label}
              </label>
            ))}
          </div>
        </fieldset>
      ))}
      {unanswered.length > 0 && (
        <Button size="sm" variant="ghost" className="w-fit" onClick={markRemainingUnknown}>
          Mark {unanswered.length} unanswered as unknown
        </Button>
      )}
      <label className="grid gap-1 text-sm">Note (optional)
        <Input value={note} maxLength={NOTE_MAX_LENGTH} onChange={(e) => setNote(e.target.value)} placeholder="Anything the choices above don't capture" aria-describedby={`${proposal.proposal_id}-note-count`} />
        <span id={`${proposal.proposal_id}-note-count`} className="text-xs text-muted-foreground">{note.length}/{NOTE_MAX_LENGTH}</span>
      </label>
      <label className="grid gap-1 text-sm">Ticket or reference<Input value={reference} onChange={(e) => setReference(e.target.value)} placeholder="Optional external reference" /></label>
      {error && <p role="alert" className="text-sm text-destructive">{error}</p>}
      <Button className="w-fit" disabled={busy || !valid} variant={decision === "REJECTED" ? "destructive" : "default"} onClick={submit}>
        {busy ? "Recording decision..." : decision === "APPROVED" ? "Approve remediation" : "Reject remediation"}
      </Button>
    </div>
  );
}

export default function RemediationPanel({ scanId, service = scanService }: { scanId: string; service?: ScanApi }) {
  const [proposals, setProposals] = useState<RemediationProposal[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  useEffect(() => {
    let active = true; setProposals(null); setError(null);
    void service.getRemediations(scanId).then((result) => { if (active) setProposals(result.proposals); })
      .catch((err) => { if (active) setError(classifyError(err).message); });
    return () => { active = false; };
  }, [scanId, service]);

  const update = (value: RemediationProposal) => setProposals((items) => items?.map((item) => item.proposal_id === value.proposal_id ? value : item) ?? [value]);
  return (
    <Card><CardHeader><CardTitle>Remediation decisions</CardTitle></CardHeader><CardContent className="grid gap-4">
      <p className="text-sm text-muted-foreground">Approval authorizes this evidence-bound recommendation to advance. It does not apply code, prove the fix, merge, or deploy anything.</p>
      {error && <p role="alert" className="text-sm text-destructive">{error}</p>}
      {proposals === null && !error && <p className="text-sm text-muted-foreground">Loading proposals...</p>}
      {proposals?.length === 0 && <p className="text-sm text-muted-foreground">No actionable findings produced remediation proposals.</p>}
      {proposals?.map((proposal) => (
        <section key={proposal.proposal_id} className="grid gap-3 rounded-lg border p-4">
          <div className="flex flex-wrap items-center gap-2"><Badge>{proposal.action}</Badge><Badge variant="outline">{proposal.status}</Badge><code className="text-sm">{proposal.subject_label}</code></div>
          <p className="font-medium">{proposal.recommendation}</p><p className="text-sm text-muted-foreground">{proposal.rationale}</p>
          <dl className="grid gap-2 text-sm sm:grid-cols-2"><div><dt className="text-muted-foreground">Expected risk reduction</dt><dd>{proposal.expected_risk_reduction}</dd></div><div><dt className="text-muted-foreground">Compatibility impact</dt><dd>{proposal.compatibility_impact}</dd></div></dl>
          {proposal.proposed_value && <p className="text-sm">Version: <code>{proposal.current_value ?? "unknown"}</code> → <code>{proposal.proposed_value}</code></p>}
          <details className="text-sm"><summary className="cursor-pointer font-medium">Evidence and uncertainty</summary><ul className="mt-2 grid gap-1 text-xs">{proposal.evidence.map((e, i) => <li key={`${e.path}-${i}`}><code>{e.path}</code> · {e.kind} · {e.locator}</li>)}{proposal.uncertainty.map((u) => <li key={u} className="text-muted-foreground">Uncertainty: {u}</li>)}</ul></details>
          {proposal.status === "PENDING" ? <DecisionForm scanId={scanId} proposal={proposal} service={service} onDecided={update} /> : <DecisionRecord proposal={proposal} />}
        </section>
      ))}
    </CardContent></Card>
  );
}

import type { Evidence } from "@/types/graph";

export type RemediationAction = "upgrade" | "replace" | "remove" | "pin" | "mitigate" | "block" | "security_review";
export type ProposalStatus = "PENDING" | "APPROVED" | "REJECTED" | "SUPERSEDED";
export type DecisionType = "APPROVED" | "REJECTED";
/** Legacy free-form factors; only present on decisions recorded before structured assessments. */
export type DecisionFactor =
  | "SECURITY_RISK" | "EXPLOITABILITY" | "DEPENDENCY_PATH" | "APPLICATION_CONTEXT"
  | "COMPATIBILITY" | "BUSINESS_IMPACT" | "TEST_EVIDENCE" | "SOURCE_CONFIDENCE"
  | "INCOMPLETE_EVIDENCE" | "LICENSE_OR_POLICY" | "OPERATIONAL_RISK"
  | "ROLLBACK_READINESS" | "ALTERNATIVE_AVAILABLE" | "OTHER";

/** Every dimension accepts UNKNOWN: an honest "don't know" is a valid answer. */
export interface ReviewAssessment {
  production_usage: "IN_PRODUCTION" | "NOT_IN_PRODUCTION" | "DEV_OR_TEST_ONLY" | "UNKNOWN";
  compatibility: "COMPATIBLE" | "MINOR_CHANGES" | "BREAKING" | "UNKNOWN";
  test_confidence: "HIGH" | "PARTIAL" | "NONE" | "UNKNOWN";
  ownership: "OWNER_CONFIRMED" | "OWNER_IDENTIFIED" | "NO_OWNER" | "UNKNOWN";
  alternatives: "ALTERNATIVE_PREFERRED" | "ALTERNATIVE_AVAILABLE" | "NO_ALTERNATIVE" | "UNKNOWN";
  timing: "IMMEDIATE" | "NEXT_RELEASE" | "BACKLOG" | "UNKNOWN";
}

export const NOTE_MAX_LENGTH = 280;

export interface RemediationDecisionCreate {
  decision: DecisionType;
  decided_by: string;
  assessment: ReviewAssessment;
  note: string | null;
  external_reference: string | null;
  expected_proposal_version: number;
}

export interface RemediationDecision {
  decision_id: string;
  proposal_id: string;
  decision: DecisionType;
  decided_by: string;
  /** Generated by Kestral from the assessment, or the reviewer's text for legacy records. */
  reason: string;
  reason_source: "GENERATED" | "REVIEWER_WRITTEN";
  explanation_template: string | null;
  assessment: ReviewAssessment | null;
  note: string | null;
  factors: DecisionFactor[];
  conditions: string | null;
  alternative: string | null;
  external_reference: string | null;
  repository_commit: string;
  finding_digest: string;
  proposal_digest: string;
  decided_at: string;
}

export interface RemediationProposal {
  proposal_id: string;
  scan_id: string;
  finding_id: string;
  action: RemediationAction;
  subject_label: string;
  current_value: string | null;
  proposed_value: string | null;
  recommendation: string;
  rationale: string;
  expected_risk_reduction: "high" | "medium" | "low" | "unknown";
  compatibility_impact: "high" | "medium" | "low" | "unknown";
  evidence: Evidence[];
  uncertainty: string[];
  repository_commit: string;
  finding_digest: string;
  proposal_digest: string;
  status: ProposalStatus;
  version: number;
  created_at: string;
  decision: RemediationDecision | null;
}

export interface RemediationList {
  schema_version: "1.0";
  scan_id: string;
  proposals: RemediationProposal[];
}

import { fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import RemediationPanel from "@/components/remediation/RemediationPanel";
import type { ScanApi } from "@/services/api";
import type { RemediationProposal } from "@/types/remediation";

const proposal: RemediationProposal = {
  proposal_id: "rem_1", scan_id: "scan_1", finding_id: "finding_1", action: "upgrade",
  subject_label: "example@1.0.0", current_value: "1.0.0", proposed_value: "1.0.1",
  recommendation: "Evaluate upgrading example to 1.0.1.", rationale: "A fixed version is reported.",
  expected_risk_reduction: "high", compatibility_impact: "unknown",
  evidence: [{ path: "package-lock.json", kind: "lockfile", locator: "example" }], uncertainty: [],
  repository_commit: "a".repeat(40), finding_digest: "b".repeat(64), proposal_digest: "c".repeat(64),
  status: "PENDING", version: 1, created_at: "2026-11-24T00:00:00Z", decision: null,
};

function service(): ScanApi {
  return {
    createScan: vi.fn(), getScan: vi.fn(), getInventory: vi.fn(), getSbom: vi.fn(),
    getGraph: vi.fn(), getFindings: vi.fn(),
    getRemediations: vi.fn(async () => ({ schema_version: "1.0" as const, scan_id: "scan_1", proposals: [proposal] })),
    decideRemediation: vi.fn(async (_id, _proposal, body) => {
      const decisionBody = {
        decision: body.decision, decided_by: body.decided_by,
        reason: "Approved the proposed upgrade of example@1.0.0. Not assessed (reported as unknown): ownership.",
        reason_source: "GENERATED" as const, explanation_template: "assessment-v1",
        assessment: body.assessment, note: body.note, factors: [],
        conditions: null, alternative: null, external_reference: body.external_reference,
      };
      return {
        ...proposal, status: body.decision, version: 2,
        decision: { ...decisionBody, decision_id: "dec_1", proposal_id: "rem_1", repository_commit: proposal.repository_commit,
          finding_digest: proposal.finding_digest, proposal_digest: proposal.proposal_digest, decided_at: "2026-11-24T01:00:00Z" },
      };
    }),
  };
}

describe("RemediationPanel", () => {
  it("records a decision from structured choices without requiring written reasoning", async () => {
    const api = service();
    vi.spyOn(window, "confirm").mockReturnValue(true);
    const announced: unknown[] = [];
    window.addEventListener("kestral:decision-recorded", (e) => announced.push((e as CustomEvent).detail));
    render(<RemediationPanel scanId="scan_1" service={api} defaultOpen />);
    fireEvent.click(await screen.findByRole("button", { name: /example@1\.0\.0/ }));
    expect(await screen.findByText(/Evaluate upgrading/)).toBeInTheDocument();
    const submit = screen.getByRole("button", { name: "Approve remediation" });
    expect(submit).toBeDisabled();
    fireEvent.change(screen.getByLabelText("Reviewer identity"), { target: { value: "alice@example.com" } });

    const production = screen.getByRole("group", { name: "Is the affected code used in production?" });
    fireEvent.click(within(production).getByLabelText("Yes, in production"));
    fireEvent.click(within(screen.getByRole("group", { name: "Will the change be compatible?" })).getByLabelText("Compatible"));
    expect(submit).toBeDisabled();

    fireEvent.click(screen.getByRole("button", { name: "Mark 4 unanswered as unknown" }));
    expect(within(production).getByLabelText("Yes, in production")).toBeChecked();
    expect(within(screen.getByRole("group", { name: "Who owns the affected code?" })).getByLabelText("Unknown")).toBeChecked();
    expect(submit).toBeEnabled();

    fireEvent.click(submit);
    await waitFor(() => expect(api.decideRemediation).toHaveBeenCalled());
    const body = vi.mocked(api.decideRemediation).mock.calls[0][2];
    expect(body.assessment).toEqual({
      production_usage: "IN_PRODUCTION", compatibility: "COMPATIBLE", test_confidence: "UNKNOWN",
      ownership: "UNKNOWN", alternatives: "UNKNOWN", timing: "UNKNOWN",
    });
    expect(body.note).toBeNull();
    expect(body).not.toHaveProperty("reason");
    expect(await screen.findByText(/Audit explanation:/)).toBeInTheDocument();
    expect(announced).toEqual([{ scanId: "scan_1", source: "remediation" }]);
    expect(screen.getByText(/Generated by Kestral/)).toBeInTheDocument();
  });

  it("caps the optional note", async () => {
    render(<RemediationPanel scanId="scan_1" service={service()} defaultOpen />);
    fireEvent.click(await screen.findByRole("button", { name: /example@1\.0\.0/ }));
    const note = await screen.findByLabelText(/Note \(optional\)/);
    expect(note).toHaveAttribute("maxLength", "280");
  });

  it("starts collapsed with status counts and expands on demand", async () => {
    render(<RemediationPanel scanId="scan_1" service={service()} />);
    const header = await screen.findByRole("button", { name: /Remediation decisions/ });
    expect(header).toHaveAttribute("aria-expanded", "false");
    expect(await screen.findByText("1 pending")).toBeInTheDocument();
    expect(screen.queryByText(/Evaluate upgrading/)).toBeNull();

    fireEvent.click(header);
    const row = await screen.findByRole("button", { name: /example@1\.0\.0/ });
    expect(row).toHaveAttribute("aria-expanded", "false");
    expect(screen.queryByLabelText("Reviewer identity")).toBeNull();

    fireEvent.click(row);
    expect(row).toHaveAttribute("aria-expanded", "true");
    fireEvent.change(screen.getByLabelText("Reviewer identity"), { target: { value: "alice" } });
    fireEvent.click(row); // collapse
    fireEvent.click(row); // reopen: the draft is still there
    expect(screen.getByLabelText("Reviewer identity")).toHaveValue("alice");
  });

  it("filters proposals by status from the dropdown", async () => {
    render(<RemediationPanel scanId="scan_1" service={service()} defaultOpen />);
    const select = await screen.findByLabelText("Filter proposals by status");
    fireEvent.change(select, { target: { value: "APPROVED" } });
    expect(screen.getByText("No proposals with this status.")).toBeInTheDocument();
    fireEvent.change(select, { target: { value: "PENDING" } });
    expect(screen.getByRole("button", { name: /example@1\.0\.0/ })).toBeInTheDocument();
  });
});
